const { contextBridge, ipcRenderer } = require("electron");

contextBridge.exposeInMainWorld("smartTrans", {
  listTodos: () => ipcRenderer.invoke('todos-list'),
  saveTodo: payload => ipcRenderer.invoke('todos-save', payload),
  completeTodo: (id, complete) => ipcRenderer.invoke('todos-complete', id, complete),
  removeTodo: id => ipcRenderer.invoke('todos-remove', id),
  onTodoSelection: callback => ipcRenderer.on('todo-selection', (_event, payload) => callback(payload)),
  openDesktopTodos: () => ipcRenderer.invoke('todo-view-open'),
  onTodosChanged: callback => ipcRenderer.on('todos-changed', () => callback()),
  exportBackup: data => ipcRenderer.invoke("backup-export", data),
  openBackup: () => ipcRenderer.invoke("backup-open"),
  restoreBackupFavorites: () => ipcRenderer.invoke("backup-restore-favorites"),
  listFavorites: () => ipcRenderer.invoke("favorites-list"),
  saveFavorite: payload => ipcRenderer.invoke("favorites-save", payload),
  removeFavorite: id => ipcRenderer.invoke("favorites-remove", id),
  onFavoriteSelection: callback => ipcRenderer.on("favorite-selection", (_event, payload) => callback(payload)),
  onFavoritesChanged: callback => ipcRenderer.on('favorites-changed', () => callback()),
  setPinned: enabled => ipcRenderer.invoke("window-pin", enabled),
  setMini: enabled => ipcRenderer.invoke("window-mini", enabled),
  notesStatus: () => ipcRenderer.invoke('notes-status'),
  setNotesEnabled: enabled => ipcRenderer.invoke('notes-enabled', enabled),
  openNotes: () => ipcRenderer.invoke('notes-open'),
  speak: payload => ipcRenderer.invoke("speech-start", payload),
  stopSpeech: () => ipcRenderer.invoke("speech-stop"),
  onSpeechState: callback => ipcRenderer.on("speech-state", (_event, state) => callback(state)),
  onSpeechAction: callback => ipcRenderer.on("speech-action", (_event, action) => callback(action)),
  translate: (payload) => ipcRenderer.invoke("translate", payload),
  setBrowserProvider: provider => ipcRenderer.send('browser-provider', provider),
  openBrowserExtensionFolder: () => ipcRenderer.invoke('browser-extension-folder'),
  installBrowserBridge: id => ipcRenderer.invoke('browser-install', id),
  learningAssist: (payload) => ipcRenderer.invoke("learning-assist", payload),
  cancel: (requestId) => ipcRenderer.invoke("cancel-translation", requestId),
  onProgress: (callback) => ipcRenderer.on("translation-progress", (_event, payload) => callback(payload)),
  onEditorCommand: (callback) => ipcRenderer.on("editor-command", (_event, command) => callback(command)),
  onDesktopAction: (callback) => ipcRenderer.on("desktop-action", (_event, action) => callback(action)),
  desktopStatus: () => ipcRenderer.invoke("desktop-status"),
  readJira: (url) => ipcRenderer.invoke("jira-read", url),
  jiraConnectionStatus: (url) => ipcRenderer.invoke("jira-connection-status", url),
  connectJira: (payload) => ipcRenderer.invoke("jira-connect", payload),
  disconnectJira: (url) => ipcRenderer.invoke("jira-disconnect", url),
  jiraBrowserData: (url) => ipcRenderer.invoke("jira-browser-data", url),
  jiraBrowserComments: (url) => ipcRenderer.invoke("jira-browser-comments", { url }),
  importJiraClipboard: (url) => ipcRenderer.invoke("jira-import-clipboard", url),
  openExternal: (url) => ipcRenderer.invoke("open-external", url),
  status: () => ipcRenderer.invoke("cli-status"),
  copy: (text) => ipcRenderer.invoke("copy-text", text),
  onTranslateSelection: (callback) => ipcRenderer.on("translate-selection", () => callback()),
});
